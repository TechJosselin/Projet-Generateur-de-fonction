#include <stdio.h>

#include "esp_err.h"

#include "initialisation.h"

/*===============================================================================================
MAIN
===============================================================================================*/
void app_main(void)
{
    esp_err_t err;

    err = System_Init();
    if (err != ESP_OK)
    {
        printf("Erreur initialisation systeme : %s\n", esp_err_to_name(err));
        return;
    }

    printf("Initialisation systeme OK.\n");
    printf("Bus I2C partage pret pour OLED, EEPROM et EPOT.\n");
}

